#!/usr/bin/env bash
# Prepares /opt/zenxpos/production on the VPS. Safe to re-run. Run as root from a copy of zenx-pos/deploy:
#   sudo bash bootstrap-production.sh [public-api-url]      (default https://retail-api.zenxpos.com)
# It installs the current deployment scripts (shared with staging), compose.yml and mysql-init, and
# creates app.env / mysql.env with generated secrets when they do not exist yet; it never overwrites
# them. It starts nothing: the production workflow deploys, and MySQL initialises the empty volume
# from mysql-init on that first deploy.
set -Eeuo pipefail

[[ $EUID -eq 0 ]] || { echo 'Run as root (sudo).' >&2; exit 2; }
source_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
public_url="${1:-https://retail-api.zenxpos.com}"
[[ "$public_url" =~ ^https://[a-z0-9.-]+$ ]] || { echo 'The public API URL must look like https://retail-api.zenxpos.com' >&2; exit 2; }
dir=/opt/zenxpos/production
stamp="$(date -u +%Y%m%dT%H%M%SZ)"
for file in remote-deploy.sh apply-migrations.sh compose.yml app.env.example mysql-init/001-schema.sql mysql-init/003-migration-baseline.sql; do
  test -s "$source_dir/$file" || { echo "Missing $source_dir/$file" >&2; exit 2; }
done
command -v openssl >/dev/null

echo '== Deployment commands (used by both staging and production)'
install -o root -g root -m 755 "$source_dir/remote-deploy.sh" /usr/local/sbin/zenxpos-deploy
install -o root -g root -m 755 "$source_dir/apply-migrations.sh" /usr/local/sbin/zenxpos-apply-migrations

echo "== $dir"
install -d -o root -g root -m 755 "$dir"
install -d -o root -g root -m 700 "$dir/backups"
if [[ -f "$dir/compose.yml" ]] && ! cmp -s "$source_dir/compose.yml" "$dir/compose.yml"; then
  cp -p "$dir/compose.yml" "$dir/compose.yml.bak-$stamp"
  echo "Previous compose.yml kept as compose.yml.bak-$stamp"
fi
install -o root -g root -m 644 "$source_dir/compose.yml" "$dir/compose.yml"

if docker volume inspect zenxpos_production_mysql >/dev/null 2>&1; then
  echo 'The production MySQL volume already exists: mysql-init is not used again, migrations keep it current.'
else
  rm -rf "$dir/mysql-init"
  install -d -o root -g root -m 755 "$dir/mysql-init"
  install -o root -g root -m 644 "$source_dir"/mysql-init/*.sql "$dir/mysql-init/"
  echo "mysql-init installed: $(cd "$dir/mysql-init" && ls | tr '\n' ' ')"
fi

secret() { openssl rand -base64 "$1" | tr -d '\n'; }
if [[ ! -f "$dir/mysql.env" ]]; then
  umask 077
  cat > "$dir/mysql.env" <<EOF
MYSQL_DATABASE=zenxpos_production
MYSQL_USER=zenxpos_app
MYSQL_PASSWORD=$(openssl rand -hex 24)
MYSQL_ROOT_PASSWORD=$(openssl rand -hex 24)
EOF
  chown root:root "$dir/mysql.env"; chmod 600 "$dir/mysql.env"
  echo 'mysql.env created with generated passwords.'
else
  echo 'mysql.env exists; left unchanged.'
fi

if [[ ! -f "$dir/app.env" ]]; then
  mysql_password="$(grep '^MYSQL_PASSWORD=' "$dir/mysql.env" | cut -d= -f2-)"
  [[ "$mysql_password" =~ ^[A-Za-z0-9]+$ ]] || { echo 'MYSQL_PASSWORD must be alphanumeric so it can be used in DATABASE_URL.' >&2; exit 1; }
  umask 077
  sed -E \
    -e "s#^PUBLIC_BASE_URL=.*#PUBLIC_BASE_URL=$public_url#" \
    -e 's#^CORS_ALLOWED_ORIGINS=.*#CORS_ALLOWED_ORIGINS=https://barcode.zenxpos.com,https://www.zenxpos.com,https://zenxpos.com#' \
    -e "s#^JWT_SECRET=.*#JWT_SECRET=$(secret 48)#" \
    -e "s#^ADMIN_SESSION_SECRET=.*#ADMIN_SESSION_SECRET=$(secret 48)#" \
    -e "s#^RESET_HMAC_SECRET=.*#RESET_HMAC_SECRET=$(secret 48)#" \
    -e "s#^INTEGRATION_CREDENTIALS_MASTER_KEY=.*#INTEGRATION_CREDENTIALS_MASTER_KEY=$(secret 32)#" \
    -e 's#^CASHFREE_ENVIRONMENT=.*#CASHFREE_ENVIRONMENT=production#' \
    -e "s#^CASHFREE_RETURN_URL=.*#CASHFREE_RETURN_URL=$public_url/api/subscription/cashfree/return?order_id={order_id}#" \
    -e "s#^DATABASE_URL=.*#DATABASE_URL=mysql://zenxpos_app:$mysql_password@mysql:3306/zenxpos_production#" \
    -e 's#^REDIS_KEY_PREFIX=.*#REDIS_KEY_PREFIX=zenxpos:production:v1:#' \
    -e 's#^\# Copy to .*#\# Production settings (generated by bootstrap-production.sh). Keep mode 600, owned by root.#' \
    -e '/^\# Production uses a different file/d' \
    -e 's#^\# Docker staging example: .*#\# Production database (Docker MySQL service "mysql").#' \
    "$source_dir/app.env.example" > "$dir/app.env"
  chown root:root "$dir/app.env"; chmod 600 "$dir/app.env"
  echo 'app.env created with generated secrets.'
else
  echo 'app.env exists; left unchanged.'
fi

echo '== Values still to fill in /opt/zenxpos/production/app.env (empty keys):'
grep -E '^[A-Z0-9_]+=$' "$dir/app.env" | cut -d= -f1 | sed 's/^/  - /' || echo '  (none)'

echo '== Deployment check'
/usr/local/sbin/zenxpos-deploy --check production
cat <<EOF

Next steps:
  1. Fill the empty keys above (Cashfree live keys, SMTP, OTP delivery, Redis) in $dir/app.env.
  2. Point DNS for ${public_url#https://} to this server and add an aaPanel reverse proxy with TLS to http://127.0.0.1:5100.
  3. In GitHub (environment "production"): PRODUCTION_URL=$public_url and PRODUCTION_DEPLOY_ENABLED=true.
  4. Merge to main. After the first deploy, create the first super-admin:
     docker exec -e ADMIN_CREATE_FIRST=true -e ADMIN_RESET_NAME='Super Admin' \\
       -e ADMIN_RESET_MOBILE='<10-digit mobile>' -e ADMIN_RESET_PASSWORD='<strong password>' \\
       zenxpos-production node dist/models/database/reset-admin.js
EOF
