-- Purchase module: suppliers, per-product buying settings, Purchase Order, GRN, Purchase
-- Invoice, Purchase Return (PRN), buyer Debit Note, Supplier Credit Note and the supplier
-- ledger. Safe to rerun on MySQL 8.0+ / TiDB.
--
-- What posts what (spec §11):
--   GRN posted        -> stock up (accepted + free qty): product_variants.variant_qty and the
--                        daily stock row (stock.purchase / stock.free_qty).
--   Invoice posted    -> supplier payable (supplier_ledger credit). Never stock.
--   PRN posted        -> stock down (stock.purchase_return). No money.
--   Debit Note posted -> payable reduced (supplier_ledger debit).
--   Credit Note posted-> payable reduced, unless it only confirms a Debit Note already posted.
--   Payment posted    -> payable reduced by amount + TDS (supplier_ledger debit); the part not
--                        allocated to invoices / the opening balance is an advance.
-- A document posts once: its status moves draft -> posted in the same transaction as the
-- postings, and supplier_ledger is unique per document.
--
-- suppliers.gst_registration: registered | composition | unregistered (GSTIN required unless
-- unregistered). visit_day: the weekday the supplier's representative visits.
-- Supplier outstanding = opening_balance + ledger credits - ledger debits (negative = advance).
-- Invoice outstanding = net_amount - adjusted_amount (debit/credit notes) - paid_amount.
--
-- Quantities are in stock units, amounts in rupees (2 decimals), purchase rates exclude GST.
-- tax_type: intra = CGST + SGST (supplier in the store's state, or no state), inter = IGST.
-- Document numbers come from purchase_sequences, one counter per client and doc_type
-- (PO, GRN, PI, PRN, DN, SCN, PAY).

