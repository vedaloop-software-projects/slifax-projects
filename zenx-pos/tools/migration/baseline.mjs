import { createHash } from 'node:crypto'
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

// A new database is created from deploy/mysql-init, which already contains every migration up to the
// baseline. 003-migration-baseline.sql records those migrations in zenxpos_schema_migrations (with the
// checksums deploy/apply-migrations.sh compares), so only migrations added later run on a new database.
//   --check  verify every recorded migration still exists with the same checksum (CI)
//   --write  record all current migrations (only when deliberately re-baselining mysql-init)
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const sqlDirectory = join(root, 'deploy/sql')
const baselineFile = join(root, 'deploy/mysql-init/003-migration-baseline.sql')
const migrationName = /^[0-9]{8,14}_[a-z0-9_]+\.sql$/

export const checksum = (file) => createHash('sha256').update(readFileSync(file)).digest('hex')

export function migrations(directory = sqlDirectory) {
  return readdirSync(directory).filter((name) => name.endsWith('.sql')).sort().map((name) => {
    if (!migrationName.test(name)) throw new Error(`Invalid migration filename: ${name}`)
    return { name, checksum: checksum(join(directory, name)) }
  })
}

export function renderBaseline(records) {
  const rows = records.map(({ name, checksum: sum }) => `  ('${name}', '${sum}')`).join(',\n')
  return `-- Generated by tools/migration/baseline.mjs. Records the migrations already contained in
-- 001-schema.sql so deploy/apply-migrations.sh does not re-run them on a new database.
CREATE TABLE IF NOT EXISTS \`zenxpos_schema_migrations\` (\`name\` VARCHAR(255) NOT NULL, \`checksum\` CHAR(64) NOT NULL, \`applied_at\` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY (\`name\`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
INSERT INTO \`zenxpos_schema_migrations\` (\`name\`, \`checksum\`) VALUES
${rows};
`
}

export function parseBaseline(text) {
  return [...text.matchAll(/\('([^']+)', '([a-f0-9]{64})'\)/g)].map((match) => ({ name: match[1], checksum: match[2] }))
}

export function checkBaseline(recorded, current) {
  const byName = new Map(current.map((row) => [row.name, row.checksum]))
  const problems = []
  if (!recorded.length) problems.push('The baseline records no migrations.')
  for (const row of recorded) {
    if (!byName.has(row.name)) problems.push(`Baselined migration ${row.name} no longer exists.`)
    else if (byName.get(row.name) !== row.checksum) problems.push(`Baselined migration ${row.name} changed after it was baselined; add a new migration instead.`)
  }
  const last = recorded.at(-1)?.name ?? ''
  const pending = current.filter((row) => !recorded.some((record) => record.name === row.name))
  for (const row of pending) if (row.name < last) problems.push(`Migration ${row.name} sorts before the baseline's last migration ${last}; new migrations must have a later date.`)
  return { problems, pending: pending.map((row) => row.name) }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const current = migrations()
  if (process.argv.includes('--write')) {
    writeFileSync(baselineFile, renderBaseline(current))
    console.log(`Baselined ${current.length} migrations in deploy/mysql-init/003-migration-baseline.sql.`)
  } else {
    if (!existsSync(baselineFile)) throw new Error('deploy/mysql-init/003-migration-baseline.sql is missing.')
    const { problems, pending } = checkBaseline(parseBaseline(readFileSync(baselineFile, 'utf8')), current)
    if (problems.length) {
      for (const problem of problems) console.error(problem)
      process.exit(1)
    }
    console.log(`Migration baseline is valid; ${pending.length} migration(s) will run on a new database after it.`)
  }
}
